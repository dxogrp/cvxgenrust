def _toml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _toml_string_list(values: list[str], indent: str = "    ") -> str:
    return "\n".join(f"{indent}{_toml_string(value)}," for value in values)


def _load_template(name: str) -> str:
    return (TEMPLATES_DIR / name).read_text(encoding="utf-8")


def _fill_template(template: str, **values: str) -> str:
    for key, value in values.items():
        template = template.replace(f"__{key}__", value)
    return template


def _comment_block(prefix: str, lines: list[str]) -> str:
    return "\n".join(f"{prefix} {line}" if line else prefix.rstrip() for line in lines)


def _generated_header_lines(artifact: str, generated_at: str, module_name: str | None = None) -> list[str]:
    lines = [
        f"Generated by {GENERATOR_DISPLAY_NAME} v{GENERATOR_VERSION}",
        f"Generated at: {generated_at}",
        f"Artifact: {artifact}",
    ]
    if module_name is not None:
        lines.insert(3, f"Problem module: {module_name}")
    return lines


def _generated_header(prefix: str, artifact: str, generated_at: str, module_name: str | None = None) -> str:
    lines = _generated_header_lines(artifact, generated_at, module_name=module_name)
    if not prefix:
        return "\n".join(lines)
    return _comment_block(prefix, lines)


def _rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _supported_clarabel_settings(spec: ProblemSpec) -> list[str]:
    settings = [
        *_CLARABEL_BOOL_SETTINGS,
        *_CLARABEL_U32_SETTINGS,
        *_CLARABEL_F64_SETTINGS,
        *_CLARABEL_STRING_SETTINGS,
    ]
    if spec.cone_dims.psd:
        settings.extend(_CLARABEL_CHORDAL_BOOL_SETTINGS)
        settings.extend(_CLARABEL_CHORDAL_STRING_SETTINGS)
    return settings


def _render_python_settings_match_arms(spec: ProblemSpec) -> str:
    return "\n".join(f'                "{name}" => {{}}' for name in _supported_clarabel_settings(spec))


def _render_python_settings_apply_code(spec: ProblemSpec) -> str:
    lines = []
    bool_settings = list(_CLARABEL_BOOL_SETTINGS)
    string_settings = list(_CLARABEL_STRING_SETTINGS)
    if spec.cone_dims.psd:
        bool_settings.extend(_CLARABEL_CHORDAL_BOOL_SETTINGS)
        string_settings.extend(_CLARABEL_CHORDAL_STRING_SETTINGS)
    for name in bool_settings:
        lines.append(f"        apply_setting!({name}, bool);")
    for name in _CLARABEL_U32_SETTINGS:
        lines.append(f"        apply_setting!({name}, u32);")
    for name in _CLARABEL_F64_SETTINGS:
        lines.append(f"        apply_setting!({name}, f64);")
    for name in string_settings:
        lines.append(f"        apply_setting!({name}, String);")
    return "\n".join(lines)


def _rustdoc_text(value: str) -> str:
    return value.replace("\n", " ").replace("\r", " ")


def _shape_text(shape: tuple[int, ...]) -> str:
    if not shape:
        return "scalar"
    return " x ".join(str(dim) for dim in shape)


def _rustdoc_block(indent: str, lines: list[str]) -> str:
    return "\n".join(f"{indent}/// {_rustdoc_text(line)}" if line else f"{indent}///" for line in lines)


def _rust_usize_slice(values: list[int] | tuple[int, ...]) -> str:
    return "&[" + ", ".join(f"{value}usize" for value in values) + "]"


def _rust_vec(values: list[object], render_value, indent: str) -> str:
    if not values:
        return "vec![]"
    entries = "\n".join(f"{indent}    {render_value(value)}," for value in values)
    return f"vec![\n{entries}\n{indent}]"


def _rust_usize_vec(values: list[int], indent: str = "") -> str:
    return _rust_vec(values, lambda value: f"{value}usize", indent)


def _rust_f64(value: float) -> str:
    if math.isnan(value):
        raise ValueError("NaN coefficients are not supported")
    if math.isinf(value):
        return "f64::INFINITY" if value > 0 else "f64::NEG_INFINITY"
    if value == 0.0:
        return "0.0"
    return repr(float(value))


def _rust_f64_vec(values: list[float], indent: str = "") -> str:
    return _rust_vec(values, _rust_f64, indent)


def _rust_static_slice(
    name: str,
    item_type: str,
    values: list[object],
    render_value,
    chunk_size: int = 12,
) -> str:
    if not values:
        return f"#[rustfmt::skip]\nstatic {name}: &[{item_type}] = &[];"

    chunks = []
    for start in range(0, len(values), chunk_size):
        chunk = values[start:start + chunk_size]
        chunks.append("    " + ", ".join(render_value(value) for value in chunk) + ",")
    return f"#[rustfmt::skip]\nstatic {name}: &[{item_type}] = &[\n" + "\n".join(chunks) + "\n];"


def _rust_static_usize_slice(name: str, values: list[int]) -> str:
    return _rust_static_slice(name, "usize", values, lambda value: f"{value}usize")


def _rust_static_f64_slice(name: str, values: list[float]) -> str:
    return _rust_static_slice(name, "f64", values, _rust_f64, chunk_size=8)


def _render_data_csr(function_name: str, const_prefix: str, spec: CsrMatrixSpec) -> str:
    return "\n\n".join(
        [
            _rust_static_usize_slice(f"{const_prefix}_INDPTR", spec.indptr),
            _rust_static_usize_slice(f"{const_prefix}_INDICES", spec.indices),
            _rust_static_f64_slice(f"{const_prefix}_DATA", spec.data),
            f"""pub(crate) fn {function_name}() -> CsrMatrix {{
    CsrMatrix {{
        rows: {spec.rows}usize,
        cols: {spec.cols}usize,
        indptr: {const_prefix}_INDPTR.to_vec(),
        indices: {const_prefix}_INDICES.to_vec(),
        data: {const_prefix}_DATA.to_vec(),
    }}
}}""",
        ]
    )


def _render_data_pattern(function_name: str, const_prefix: str, spec: MatrixPatternSpec) -> str:
    return "\n\n".join(
        [
            _rust_static_usize_slice(f"{const_prefix}_INDICES", spec.indices),
            _rust_static_usize_slice(f"{const_prefix}_INDPTR", spec.indptr),
            f"""pub(crate) fn {function_name}() -> MatrixPattern {{
    MatrixPattern {{
        rows: {spec.rows}usize,
        cols: {spec.cols}usize,
        indices: {const_prefix}_INDICES.to_vec(),
        indptr: {const_prefix}_INDPTR.to_vec(),
    }}
}}""",
        ]
    )


def _indent_rust_block(block: str, indent: str) -> str:
    return "\n".join(f"{indent}{line}" if line else line for line in block.splitlines())


